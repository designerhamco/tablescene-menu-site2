export function translateMenuText(text: string, locale: SupportedLocale): string {
  if (locale === "ko") return text;
  const index = locale === "en" ? 0 : locale === "ja" ? 1 : 2;
  return MENU_UI_COPY[text]?.[index] ?? text;
}

export function formatMenuMoney(value: number, locale: SupportedLocale) {
  const amount = new Intl.NumberFormat(locale === "ko" ? "ko-KR" : locale).format(value);
  return locale === "ko" ? amount + "원" : "₩" + amount;
}
